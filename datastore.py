"""Provider-neutral SQL access layer.

Local: sqlite3 file. Hosted: any PostgreSQL DSN in DATABASE_URL.
Business logic uses portable SQL and qmark parameters. No hosted-provider SDK.
"""
from __future__ import annotations

import os
import sqlite3
from pathlib import Path
import pandas as pd


class PostgresConnection:
    """Minimal sqlite-like surface over psycopg 3 with explicit transactions.

    PostgreSQL statements outside `with db:` are committed individually via
    autocommit; `with db:` groups a whole import atomically.
    """

    backend = 'postgresql'

    def __init__(self, dsn: str):
        import psycopg
        self._connection = psycopg.connect(dsn, autocommit=True, connect_timeout=15)
        self._transaction = None

    def execute(self, query: str, params=()):
        # All project queries use positional qmark parameters. Do not interpolate
        # values into SQL, which would introduce SQL-injection and quoting bugs.
        return self._connection.execute(query.replace('?', '%s'), tuple(params))

    def executescript(self, script: str):
        # Project schema scripts comprise ordinary CREATE TABLE/INDEX statements.
        # PostgreSQL supports the same DDL except the SQLite AUTOINCREMENT token.
        script = script.replace('run_id INTEGER PRIMARY KEY AUTOINCREMENT',
                                'run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        with self:
            for statement in script.split(';'):
                if statement.strip():
                    self.execute(statement)

    def __enter__(self):
        if self._transaction is not None:
            raise RuntimeError('Nested transaction contexts are not supported')
        self._transaction = self._connection.transaction()
        self._transaction.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        transaction = self._transaction
        self._transaction = None
        return transaction.__exit__(exc_type, exc, tb)

    def commit(self):
        # autocommit outside explicit context; inside, commit at context exit.
        pass

    def close(self):
        self._connection.close()


def connect(path=None, *, url=None):
    """DATABASE_URL selects PostgreSQL; otherwise use the existing SQLite file."""
    url = url if url is not None else os.environ.get('DATABASE_URL', '').strip()
    if url:
        if not url.startswith(('postgresql://', 'postgres://')):
            raise ValueError('DATABASE_URL must be a PostgreSQL connection URL')
        return PostgresConnection(url)
    if path is None:
        path = os.environ.get('NUTRITION_DB',
              str(Path(__file__).resolve().parent / 'nutrition_analytics.sqlite'))
    return sqlite3.connect(str(path))


def read_frame(db, query: str, params=()):
    """Read DataFrame using a DBAPI cursor; works with sqlite3 or psycopg."""
    cursor = db.execute(query, params)
    columns = [col[0] if isinstance(col, tuple) else col.name for col in (cursor.description or [])]
    return pd.DataFrame(cursor.fetchall(), columns=columns)
